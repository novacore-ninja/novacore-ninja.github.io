const ES_PREFIXES = [
  ['Products / ', 'Productos / '],
  ['Email:', 'Correo:']
];

const ORIGINAL_TEXT = new WeakMap();

function currentLanguage() {
  const urlLang = new URLSearchParams(window.location.search).get('lang');
  if (urlLang === 'en' || urlLang === 'es') {
    localStorage.setItem('siteLanguage', urlLang);
    return urlLang;
  }
  return localStorage.getItem('siteLanguage') || 'en';
}

function translateText(text, lang) {
  if (lang !== 'es') return text;
  const trimmed = text.trim();
  if (ES_TEXT[trimmed]) return text.replace(trimmed, ES_TEXT[trimmed]);
  if (trimmed.startsWith('/ ')) {
    const category = trimmed.slice(2);
    if (ES_TEXT[category]) return text.replace(category, ES_TEXT[category]);
  }
  for (const [from, to] of ES_PREFIXES) {
    if (trimmed.startsWith(from)) {
      return text.replace(from, to);
    }
  }
  return text;
}

function translatePage(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll('.language-select').forEach((select) => {
    select.value = lang;
  });

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      if (node.parentElement && (['SCRIPT', 'STYLE', 'OPTION', 'TEXTAREA'].includes(node.parentElement.tagName) || node.parentElement.closest('.brand'))) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach((node) => {
    if (!ORIGINAL_TEXT.has(node)) {
      ORIGINAL_TEXT.set(node, node.nodeValue);
    }
    const original = ORIGINAL_TEXT.get(node);
    node.nodeValue = translateText(original, lang);
  });
}

function mailProduct(name) {
  const lang = currentLanguage();
  const subject = encodeURIComponent((lang === 'es' ? 'Consulta sobre ' : 'Inquiry for ') + name);
  const body = lang === 'es'
    ? 'Hola,\n\nEstoy interesado en ' + name + '. Por favor envie la ficha tecnica, MOQ, detalles de embalaje y cotizacion.\n\nSaludos,'
    : 'Hello,\n\nI am interested in ' + name + '. Please send technical datasheet, MOQ, packing details, and quotation.\n\nBest regards,';
  window.location.href = 'mailto:' + SITE_EMAIL + '?subject=' + subject + '&body=' + encodeURIComponent(body);
}

document.addEventListener('DOMContentLoaded', function(){
  const toggle = document.querySelector('.nav-toggle');
  const menu = document.querySelector('.menu');
  if (toggle && menu) {
    toggle.addEventListener('click', function(){
      const open = menu.classList.toggle('open');
      toggle.setAttribute('aria-expanded', String(open));
    });
  }

  document.querySelectorAll('.language-select').forEach((select) => {
    select.addEventListener('change', function(){
      localStorage.setItem('siteLanguage', select.value);
      translatePage(select.value);
    });
  });

  translatePage(currentLanguage());
});
